public class Exercicio_2 {

  /* 2 Contador com While: Crie um laço while que imprima os números de 1 a 10 no console. */
  
  public static void main(String[] args) {
      
    int contador = 0;
    while (contador < 10) {
      contador++;
      System.out.println("Contador: " + (contador));
    }
  }
}
